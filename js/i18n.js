// t("board", {route: "Bus 101", stop: "DC Office"}) -> "Board Bus 101 at DC Office"
function t(key, values = {}) {
  let text = TEXT[currentLang][key] ?? TEXT.en[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll("{" + name + "}", value);
  }
  return text;
}
